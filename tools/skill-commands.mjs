// Fixed migration-target rendering and actual candidate rendering are separate.
// Target generation never executes a CLI; candidate rendering never overwrites
// the fixed target unless an explicit output path is supplied by the caller.
import { spawnSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeFileSync, readFileSync } from 'node:fs';

const repository = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
function option(name) {
  const index = argv.indexOf(name);
  if (index < 0) return undefined;
  if (!argv[index + 1] || argv[index + 1].startsWith('--')) throw new Error(`${name} needs a value`);
  return argv[index + 1];
}
const binary = option('--bin');
const outputArg = option('--output');
if (binary && argv.includes('--target')) throw new Error('choose --target or --bin, not both');
if (binary && !outputArg) throw new Error('--bin requires an explicit --output; the fixed target must not be replaced');
const output = resolve(outputArg ?? join(repository, 'tests/rust-skill-usage/baselines/go3.2.2-commands.md'));
let commands;
const target = !binary;
if (target) {
  const fixture = JSON.parse(readFileSync(join(repository, 'tests/rust-parity/go-3.2.2.manifest.json'), 'utf8'));
  if (fixture.oracle?.commit !== '0bec60e4406f5d5dc155ee25cef44f9a710e37e8') throw new Error('unexpected target oracle');
  commands = fixture.commands.map(command => ({ ...command, summary: command.summary
    .replace('workspace, data, LuaLS and source checks', 'workspace, data, Emmy engine and source checks')
    .replace('a request-scoped LuaLS session', 'request-scoped Emmy analysis')
    .replace('opt-in LuaLS broker', 'opt-in native Source session')
    .replace('for bundled LuaLS using', 'for Emmy analysis using'),
  }));
} else {
  const run = spawnSync(resolve(binary), ['describe', '--format=json'], {
    cwd: repository, encoding: 'utf8', shell: false, windowsHide: true, timeout: 300000,
  });
  if (run.error) throw run.error;
  if (run.status !== 0) throw new Error(`describe failed: ${run.status}\n${run.stdout}\n${run.stderr}`);
  const envelope = JSON.parse(run.stdout);
  if (!envelope.ok || !Array.isArray(envelope.result?.commands)) throw new Error('describe returned no command contracts');
  commands = envelope.result.commands;
}
const groups = new Map();
for (const command of commands) {
  const group = command.path.split(' ')[0];
  if (!groups.has(group)) groups.set(group, []);
  groups.get(group).push(command);
}
const lines = target ? [
  '<!-- Fixed Go 3.2.2 command/flag target: 0bec60e4406f5d5dc155ee25cef44f9a710e37e8.',
  '     Generated by tools/skill-commands.mjs --target; engine descriptions adapted for Rust. -->',
  '', '# Command reference', '',
  `${commands.length} commands in the fixed Go target. This Rust candidate is still incomplete;`,
  'consult its actual describe/help and [candidate boundaries](source-candidate.md).',
  'These rows do not claim implementation or acceptance. Every target command accepts `--format text|json|jsonl`;',
] : [
  '<!-- Generated from the explicitly selected candidate describe output. -->',
  '', '# Candidate command reference', '',
  `${commands.length} declared candidate commands. Declaration is not implementation or acceptance evidence.`,
  'Every declared command accepts `--format text|json|jsonl`;',
];
lines.push('`--help` works on the root and on any command. Read the JSON envelope, not',
  'just the exit code; preserve capture IDs and partial/truncated warnings.');
for (const group of [...groups.keys()].sort()) {
  lines.push('', `## ${group}`, '');
  for (const command of groups.get(group)) {
    const args = command.arguments?.length ? ` ${command.arguments.join(' ')}` : '';
    lines.push(`- \`${command.path}${args}\` — ${command.mutates ? 'mutates' : 'read-only'}. ${command.summary}`);
    if (command.flags?.length) lines.push(`  Flags: ${command.flags.map(flag => `\`${flag}\``).join(', ')}.`);
  }
}
const generated = `${lines.join('\n')}\n`;
if (argv.includes('--check')) {
  if (readFileSync(output, 'utf8').replaceAll('\r\n', '\n') !== generated) {
    throw new Error(`skill command reference is stale; regenerate with ${target ? '--target' : '--bin and the same explicit --output'}`);
  }
} else writeFileSync(output, generated, 'utf8');
process.stdout.write(`${output}\n`);
