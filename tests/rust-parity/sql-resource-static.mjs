// Source-derived arithmetic/declaration check; never executes Rust or Go.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const read = p => readFileSync(p, 'utf8');
const map = JSON.parse(read('tests/rust-parity/sql-resource-test-map.json'));
for (const test of map.tests) assert.match(read(test.file), new RegExp(`fn ${test.test}\\(`));
const raw = Buffer.alloc(1 << 20, 'x'); raw.write('//'); raw[raw.length - 1] = 10;
assert.equal(createHash('sha256').update(raw).digest('hex'), 'db8236835a7df60fe4e1ae1e42ffa317a51f0a4311dd4b493458acdcc713d38b');
assert.equal(16 * raw.length * (4 + 1), 80 << 20);
assert.equal(16 * raw.length * (8 + 1), 144 << 20);
assert.ok((80 << 20) < (128 << 20));
assert.ok((144 << 20) < (512 << 20));
const budget = read('crates/lycheedev-data/src/resource.rs');
assert.match(budget, /decode_work: 100_000_000/);
assert.match(budget, /retained_bytes: 512 << 20/);
assert.match(budget, /metadata_bytes: 128 << 20/);
assert.match(budget, /let next_logical = self.admitted_logical\(&state, logical\)\?;\s*let next_safety = self.admitted\(state.used, safety\)\?;\s*state.logical = next_logical;/);
const sql = read('crates/lycheedev-data/src/local_query.rs');
assert.match(sql, /charge_split\(Cost::retained\(64 << 20\), Cost::default\(\)\)/);
assert.ok(sql.indexOf('let resources = budget.logical_snapshot()?') < sql.indexOf('let public_numbers = public_query_numbers(&request'));
assert.match(sql, /logicalProviderParityComplete":ids.is_empty\(\)/);
console.log(JSON.stringify({status:'PASS',kind:'source-derived arithmetic/declaration only',testDeclarations:map.tests.length,rust:'NOT_RUN',go:'NOT_RUN'}));
