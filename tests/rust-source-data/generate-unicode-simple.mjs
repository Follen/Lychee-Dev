// Reproducible Unicode simple casing, matching the frozen Go Unicode17 table.
import {readFileSync,writeFileSync,copyFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const input=process.argv[2]??'.tmp/rust-unicode-17/UnicodeData.txt';
const raw=readFileSync(input);
const expected='2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c';
if(createHash('sha256').update(raw).digest('hex')!==expected)throw Error('Fixed official Unicode17 bytes differ');
const maps={UPPER:[],LOWER:[]};
for(const line of raw.toString('utf8').trim().split('\n')){
 const f=line.trimEnd().split(';'),cp=parseInt(f[0],16);
 for(const [name,index]of [['UPPER',12],['LOWER',13]])if(f[index])maps[name].push([cp,parseInt(f[index],16)]);
}
let out=`// Generated by tests/rust-source-data/generate-unicode-simple.mjs.\n// Source https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt\n// SHA256 ${expected}; Unicode License V3, ../UNICODE-LICENSE.\n// Simple one-scalar mapping; no contextual/full case expansion.\n`;
out+='pub(crate) fn map(c: char, upper: bool) -> char {\n    let table = if upper { UPPER } else { LOWER };\n    table.binary_search_by_key(&(c as u32), |(from, _)| *from).ok().and_then(|i| char::from_u32(table[i].1)).unwrap_or(c)\n}\n';
for(const [name,rows]of Object.entries(maps))out+=`const ${name}: &[(u32, u32)] = &[\n${rows.map(([a,b])=>`    (0x${a.toString(16)}, 0x${b.toString(16)}),`).join('\n')}\n];\n`;
writeFileSync('crates/lycheedev-data/src/unicode_simple.rs',out);
copyFileSync('.tmp/rust-unicode-17/LICENSE','crates/lycheedev-data/UNICODE-LICENSE');
