#!/usr/bin/env python3
"""Generate ONLY Unicode simple-fold equivalence representatives from Go1.27.1.
No Rust/Go compiler or target program runs. --check verifies byte reproducibility.
"""
import argparse
import bisect
import hashlib
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
COMMIT = "862c888e612ac346c7c4d99c9392bdfd265f33b0"
SOURCES = {
    "tables.go.txt": ("src/unicode/tables.go", "ac0e5d5d1b58ed4b02d7cb4a0085bdefbdb4f7aae6fadddbc9477f8463da8bd8"),
    "letter.go.txt": ("src/unicode/letter.go", "b35a6d259313cef88d07e9e4027b8bd72c60ae140418f5be2c41a2ecea6074fe"),
    "strings.go.txt": ("src/strings/strings.go", "a81bdf73a308277c322e35d0c602e3813f57b6f769c091f8f8962c8884a45ea3"),
    "LICENSE": ("LICENSE", "911f8f5782931320f5b8d1160a76365b83aea6447ee6c04fa6d5591467db9dad"),
}

def digest(raw):
    return hashlib.sha256(raw).hexdigest()

def build():
    for name, (_, expected) in SOURCES.items():
        if digest((HERE / name).read_bytes()) != expected:
            raise ValueError(f"fixed Go source hash mismatch: {name}")
    source = (HERE / "tables.go.txt").read_text()
    assert 'const Version = "17.0.0"' in source
    def body(start):
        return source.split(start, 1)[1].split("\n}", 1)[0]
    ascii_fold = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]+)", body("var asciiFold = [MaxASCII + 1]uint16{"))]
    assert len(ascii_fold) == 128
    orbit = {int(a, 16): int(b, 16) for a, b in re.findall(r"\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}", body("var caseOrbit = []foldPair{"))}
    ranges = []
    for a, b, deltas in re.findall(r"\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+), d\{([^}]+)\}\}", body("var _CaseRanges = []CaseRange{")):
        values = [0x110000 if v.strip() == "UpperLower" else int(v) for v in deltas.split(",")]
        assert len(values) == 3
        ranges.append((int(a, 16), int(b, 16), values))
    assert ranges and all(a[1] < b[0] for a, b in zip(ranges, ranges[1:]))
    starts = [r[0] for r in ranges]
    def convert(r, start, deltas, case):
        delta = deltas[case]
        return start + (((r-start) & ~1) | (case & 1)) if delta > 0x10ffff else r + delta
    def simple_fold(r):
        # Exact order from fixed unicode.SimpleFold, including self-folding
        # Turkish dotted/dotless I overrides before ordinary case ranges.
        if r < 128:
            return ascii_fold[r]
        if r in orbit:
            return orbit[r]
        index = bisect.bisect_right(starts, r) - 1
        if index >= 0:
            start, end, deltas = ranges[index]
            if r <= end:
                lower = convert(r, start, deltas, 1)
                return lower if lower != r else convert(r, start, deltas, 0)
        return r
    pairs = []
    max_orbit = 0
    # Every Unicode scalar is considered. Surrogates stay identity under Go
    # SimpleFold and are decoded as RuneError at the UTF-16 input boundary.
    for scalar in range(0x110000):
        orbit_members = [scalar]
        current = simple_fold(scalar)
        while current != scalar:
            assert current not in orbit_members and len(orbit_members) < 16
            orbit_members.append(current)
            current = simple_fold(current)
        max_orbit = max(max_orbit, len(orbit_members))
        representative = min(orbit_members)
        if representative != scalar:
            pairs.append((scalar, representative))
    text = '// @generated by go_unicode/generate.py; do not edit.\n'
    text += '// Go1.27.1 Unicode 17.0.0, commit ' + COMMIT + '.\n'
    text += '// Copyright 2009 The Go Authors. BSD-3-Clause; full notice in go_unicode/LICENSE.\n'
    text += 'pub(super) const FOLD_REPRESENTATIVES: &[(u32, u32)] = &[\n'
    text += ''.join(f'    (0x{a:06x}, 0x{b:06x}),\n' for a,b in pairs)
    text += '];\n'
    identity = {
        "schema": "lycheedev.go-simple-fold-source.v1", "goVersion": "go1.27.1",
        "goCommit": COMMIT, "unicodeVersion": "17.0.0",
        "sources": [{"path":name,"upstreamPath":path,"sha256":sha,"url":f"https://github.com/golang/go/blob/{COMMIT}/{path}"} for name,(path,sha) in SOURCES.items()],
        "generatorSha256": digest(Path(__file__).read_bytes()),
        "generated": {"path":"../equal_fold_data.rs","sha256":digest(text.encode()),"representativeCount":len(pairs),"maxOrbit":max_orbit},
        "algorithm": "Exact asciiFold, caseOrbit and CaseRanges/convertCase order from pinned unicode.SimpleFold; minimum scalar of every orbit. No full folding, Unicode normalization, Rust Unicode tables or Windows ordinal comparison.",
        "execution": "Generator/static reproduction only; Rust and fixed Go execution NOT_RUN."
    }
    return {HERE.parent / "equal_fold_data.rs": text.encode(), HERE / "identity.json": (json.dumps(identity,indent=2)+"\n").encode()}

if __name__ == "__main__":
    parser=argparse.ArgumentParser()
    parser.add_argument("--check",action="store_true")
    args=parser.parse_args()
    for path,raw in build().items():
        if args.check:
            assert path.read_bytes() == raw, f"generated bytes differ: {path.name}"
        else:
            path.write_bytes(raw)
    print("Go1.27.1 SimpleFold generation verified" if args.check else "Go1.27.1 SimpleFold generated")
