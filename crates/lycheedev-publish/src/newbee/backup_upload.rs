pub struct BackupUpload {
    bundle: PathBuf,
    name: Option<String>,
}
pub enum BackupCreate {
    Bundle(BackupUpload),
    Generate {
        request: BackupGenerate,
        name: Option<String>,
    },
}
fn name(doc: &serde_json::Map<String, Value>) -> Result<Option<String>> {
    doc.get("name")
        .map(|value| {
            value
                .as_str()
                .filter(|value| !value.trim().is_empty())
                .map(str::to_owned)
                .ok_or_else(|| invalid("$.name", "backup name must not be blank"))
        })
        .transpose()
}
impl BackupUpload {
    pub fn parse(bytes: &[u8], cwd: &Path) -> Result<Self> {
        let doc = document(bytes)?;
        input_shape(Provider::Newbee, "backup", "upload")?.admit(&doc)?;
        let path = doc["bundle_file"]
            .as_str()
            .filter(|value| !value.is_empty())
            .ok_or_else(|| invalid("$.bundle_file", "select an existing backup bundle"))?;
        let bundle = std::path::absolute(cwd.join(path))?;
        if !bundle.is_file() {
            return Err(invalid("$.bundle_file", "select an existing backup bundle"));
        }
        Ok(Self {
            bundle,
            name: name(&doc)?,
        })
    }
    pub fn schema() -> Value {
        let mut schema = input_shape(Provider::Newbee, "backup", "upload")
            .unwrap()
            .schema();
        schema.as_object_mut().unwrap().remove("x-validation-scope");
        schema["properties"]["bundle_file"]["description"] = json!(
            "An unchanged lycheedev.publish.newbee.backup-bundle.v1 generated by backup generate. Every ZIP member, target, SHA256, length, font and role is admitted locally before authentication. --plan performs this admission without SDK extraction, credentials, network or submission records."
        );
        schema
    }
    pub fn plan(&self, control: &OperationControl) -> Result<Value> {
        let bundle = ValidatedBundle::open(&self.bundle, control)?;
        let result = json!({"provider":"newbee","validation":"local_bundle_and_archive_selection","bundle_sha256":bundle.sha256,"game_version_id":bundle.version,"archives":bundle.artifacts.len(),"fonts":bundle.fonts.len(),"name":self.name,"font_sdk":if bundle.fonts.is_empty(){"not_required"}else{"required_on_execution"},"remote_validation":"not_run","author_writes":0,"credential_reads":false});
        bundle.finish(Ok(output::public(result, &[])), control)
    }
}
impl BackupCreate {
    pub fn parse(bytes: &[u8], cwd: &Path) -> Result<Self> {
        let mut doc = document(bytes)?;
        input_shape(Provider::Newbee, "backup", "create")?.admit(&doc)?;
        let name = name(&doc)?;
        if doc.contains_key("bundle_file") {
            if doc
                .keys()
                .any(|key| !matches!(key.as_str(), "schema" | "bundle_file" | "name"))
            {
                return Err(invalid(
                    "$",
                    "bundle_file cannot be combined with local generation fields",
                ));
            }
            doc.insert(
                "schema".into(),
                json!("lycheedev.publish.v1.newbee.backup.upload"),
            );
            Ok(Self::Bundle(BackupUpload::parse(
                &serde_json::to_vec(&doc)?,
                cwd,
            )?))
        } else {
            doc.remove("name");
            doc.insert(
                "schema".into(),
                json!("lycheedev.publish.v1.newbee.backup.generate"),
            );
            Ok(Self::Generate {
                request: BackupGenerate::parse(&serde_json::to_vec(&doc)?, cwd)?,
                name,
            })
        }
    }
    pub fn schema() -> Value {
        let mut schema = input_shape(Provider::Newbee, "backup", "create")
            .unwrap()
            .schema();
        schema.as_object_mut().unwrap().remove("x-validation-scope");
        for (key, value) in BackupGenerate::schema()["properties"].as_object().unwrap() {
            if key != "schema" {
                schema["properties"][key] = value.clone();
            }
        }
        schema["oneOf"] = json!([{"required":["bundle_file"],"not":{"anyOf":[{"required":["game_dir"]},{"required":["game_version_id"]},{"required":["output_dir"]},{"required":["known_plugins"]},{"required":["unknown_plugins"]},{"required":["materials"]},{"required":["fonts"]},{"required":["wtf_accounts"]}]}},{"required":["game_dir","game_version_id","output_dir"],"not":{"required":["bundle_file"]}}]);
        schema["oneOf"][1]["anyOf"] = BackupGenerate::schema()["anyOf"].clone();
        schema
    }
    pub fn plan(&self, control: &OperationControl) -> Result<Value> {
        match self {
            Self::Bundle(request) => request.plan(control),
            Self::Generate { request, .. } => request.plan(control),
        }
    }
}
impl Newbee {
    pub fn create_backup(
        &mut self,
        request: &BackupCreate,
        recover_id: Option<NonZeroU64>,
    ) -> Result<Value> {
        match request {
            BackupCreate::Bundle(request) => self.upload_backup(request, recover_id),
            BackupCreate::Generate { request, name } => {
                if recover_id.is_some() {
                    return Err(ToolkitError::arguments(
                        "recover the generated backup with backup upload, its unchanged bundle_file and --id",
                    ));
                }
                let generated = request.generate(&self.control)?;
                let bundle = PathBuf::from(generated["bundle_file"].as_str().unwrap());
                self.upload_backup(
                    &BackupUpload {
                        bundle: bundle.clone(),
                        name: name.clone(),
                    },
                    None,
                )
                .map_err(|mut error| {
                    error.details["bundle_file"] = json!(bundle);
                    error.details["recovery_command"] = json!("publish newbee backup upload");
                    error
                })
            }
        }
    }
    pub fn upload_backup(
        &mut self,
        request: &BackupUpload,
        recover_id: Option<NonZeroU64>,
    ) -> Result<Value> {
        let control = self.control.clone();
        let mut bundle = ValidatedBundle::open(&request.bundle, &control)?;
        let result = self.upload_admitted(request, &mut bundle, recover_id);
        bundle.finish(result, &control)
    }
    fn upload_admitted(
        &mut self,
        request: &BackupUpload,
        bundle: &mut ValidatedBundle,
        recover_id: Option<NonZeroU64>,
    ) -> Result<Value> {
        let identity = json!({"bundle_sha256":bundle.sha256,"name":request.name,"author_subject":self.subject()?});
        let hash = storage::sha256(&storage::identity_json(&identity)?);
        let mut mutation = Mutation::open(
            &self.home,
            Provider::Newbee,
            "backup-create",
            scope(&hash),
            "create",
            &identity,
            &self.control,
        )?;
        if let Some(evidence) = mutation
            .evidence()
            .filter(|value| value["verification"] == "manifest_readback")
        {
            let mut result = evidence.clone();
            let id = wire_id(result["id"].clone())?;
            if recover_id.is_some_and(|value| value.get() != id) {
                return Err(invalid(
                    "$.id",
                    "recovery ID differs from the original backup creation",
                ));
            }
            result["reused"] = json!(true);
            result["author_writes"] = json!(0);
            drop(mutation);
            return self.backup_name(request, result);
        }
        let recovered = mutation.pending();
        if !recovered && recover_id.is_some() {
            return Err(ToolkitError::arguments(
                "--id recovers the original pending backup creation; omit it for a new upload",
            ));
        }
        let mut evidence = if recovered {
            let evidence = mutation.evidence().cloned().ok_or_else(|| {
                mutation.pending_error(
                    "retain the original backup request; its manifest receipt is pending",
                )
            })?;
            let objects = evidence["objects"]
                .as_array()
                .filter(|objects| objects.len() == bundle.artifacts.len())
                .ok_or_else(|| {
                    mutation.pending_error("original backup object references are incomplete")
                })?;
            for (artifact, value) in bundle.artifacts.iter().zip(objects) {
                let value = value.as_str().ok_or_else(|| {
                    mutation.pending_error("original backup object reference is invalid")
                })?;
                artifact.target.apply(&mut bundle.manifest, json!(value));
            }
            bundle.manifest["font_hash"] = evidence["font_hash"].clone();
            if form_hash(&bundle.manifest)? != evidence["manifest_sha256"] {
                return Err(mutation
                    .pending_error("original backup manifest identity differs from its receipt"));
            }
            evidence
        } else {
            // Resolve all local/SDK prerequisites before the first object upload.
            let cached_font = if bundle.fonts.is_empty() {
                None
            } else {
                FontSdk::cached(&self.home, &bundle.fonts, &self.control)?
            };
            let sdk = if !bundle.fonts.is_empty() && cached_font.is_none() {
                Some(FontSdk::prepare(&self.home, &self.control)?)
            } else {
                None
            };
            let versions = self.read(&Read::GameVersions)?;
            if !versions["items"].as_array().is_some_and(|rows| {
                rows.iter().any(|row| {
                    wire_uint(row["id"].clone(), 0).is_ok_and(|id| id == bundle.version.get())
                })
            }) {
                return Err(invalid(
                    "$.bundle_file.manifest.versionid",
                    "game version is absent from current platform metadata",
                ));
            }
            let before = self
                .cloud_rows()?
                .iter()
                .map(|row| wire_id(row["t_id"].clone()))
                .collect::<Result<Vec<_>>>()?;
            let mut objects = Vec::new();
            for artifact in &mut bundle.artifacts {
                let object = self.backup_object(artifact).map_err(|mut error| {
                    error.details["retained_object_count"] = json!(objects.len());
                    error
                })?;
                artifact.target.apply(&mut bundle.manifest, json!(object));
                objects.push(object);
            }
            let mut cleanup_pending = false;
            if !bundle.fonts.is_empty() {
                let uploaded = match cached_font {
                    Some(value) => value,
                    None => sdk
                        .unwrap()
                        .upload(&self.home, &bundle.fonts, &self.control)?,
                };
                bundle.manifest["font_hash"] = json!(uploaded.index);
                cleanup_pending = uploaded.cleanup_pending;
            }
            let mut evidence = json!({"objects":objects,"font_hash":bundle.manifest["font_hash"],"manifest_sha256":form_hash(&bundle.manifest)?,"before_ids":before,"create_accepted":false,"font_cleanup_pending":cleanup_pending});
            mutation.prepare(&self.control)?;
            mutation.remember(evidence.clone())?;
            let response = self
                .backup_post("/v3/share/create", &bundle.manifest, true)
                .map_err(|error| mutation.failure(error))?;
            evidence["create_accepted"] = json!(true);
            if let Ok(id) = wire_id(if response.is_object() {
                pick(&response, &["t_id", "id"])
            } else {
                response
            }) {
                evidence["created_id"] = json!(id);
            }
            mutation
                .remember(evidence.clone())
                .and_then(|_| mutation.acknowledged())
                .map_err(|_| {
                    mutation.pending_error(
                        "backup creation was accepted; finish saving its original acknowledgement",
                    )
                })?;
            evidence
        };
        let saved = evidence
            .get("created_id")
            .map(|value| wire_id(value.clone()))
            .transpose()?;
        if saved.is_some_and(|id| recover_id.is_some_and(|value| value.get() != id)) {
            return Err(invalid(
                "$.id",
                "recovery ID differs from the acknowledged backup",
            ));
        }
        let selected = saved.or(recover_id.map(NonZeroU64::get));
        if selected.is_none() && evidence["create_accepted"] != true {
            return Err(mutation.pending_error("backup creation outcome is uncertain; inspect backup list/get and recover the unchanged input with its explicit --id"));
        }
        let before = evidence["before_ids"]
            .as_array()
            .ok_or_else(|| {
                mutation.pending_error("original backup creation identity list is missing")
            })?
            .iter()
            .map(|value| wire_id(value.clone()))
            .collect::<Result<BTreeSet<_>>>()?;
        let rows = self.cloud_rows().map_err(|error| {
            mutation.readback_error("backup creation readback is pending", error)
        })?;
        let candidates = rows
            .iter()
            .filter(|row| {
                wire_id(row["t_id"].clone()).is_ok_and(|id| {
                    !before.contains(&id) && selected.is_none_or(|selected| selected == id)
                }) && manifest_matches(&bundle.manifest, row)
            })
            .collect::<Vec<_>>();
        if candidates.len() != 1 {
            return Err(mutation.pending_error("the original backup has no unique complete manifest readback; inspect backup list/get without sending create again"));
        }
        let row = candidates[0];
        let id = wire_id(row["t_id"].clone())?;
        evidence["created_id"] = json!(id);
        mutation.remember(evidence)?;
        let result = output::public(
            json!({"id":id,"operation_id":mutation.id(),"bundle_sha256":bundle.sha256,"uploaded_archives":bundle.artifacts.len(),"fonts":bundle.fonts.len(),"verification":"manifest_readback","object_verification":"http_200_acknowledgement","remote_byte_verification":"not_available","recovered":recovered,"reused":false,"author_writes":if recovered{0}else{1},"font_cleanup_pending":mutation.evidence().unwrap()["font_cleanup_pending"],"readback":cloud::summary(row)?}),
            &[],
        );
        mutation.verified_with(result.clone()).map_err(|_| {
            mutation.pending_error("backup readback matched; finish saving its verified result")
        })?;
        drop(mutation);
        self.backup_name(request, result)
    }
    fn backup_name(&mut self, request: &BackupUpload, mut result: Value) -> Result<Value> {
        if let Some(name) = &request.name {
            let id = wire_id(result["id"].clone())?;
            match self.rename_backup(&BackupRename::parse(&serde_json::to_vec(
                &json!({"schema":"lycheedev.publish.v1.newbee.backup.rename","id":id,"name":name}),
            )?)?) {
                Ok(renamed) => {
                    result["rename"] = renamed;
                }
                Err(mut error) => {
                    error.details["created_backup"] = result;
                    error.details["rename_pending"] = json!(true);
                    return Err(error);
                }
            }
        }
        Ok(result)
    }
    fn backup_object(&mut self, artifact: &mut LockedArtifact) -> Result<String> {
        let identity = json!({"sha256":artifact.sha256,"size":artifact.size,"file_type":artifact.category.key(),"author_subject":self.subject()?});
        let hash = form_hash(&identity)?;
        let mut mutation = Mutation::open(
            &self.home,
            Provider::Newbee,
            "backup-object",
            scope(&hash),
            "upload",
            &identity,
            &self.control,
        )?;
        if let Some(value) = mutation
            .evidence()
            .filter(|value| value["uploaded"] == true)
            .and_then(|value| value["file_path"].as_str())
        {
            return Ok(value.to_owned());
        }
        if mutation.pending() {
            return Err(mutation.pending_error("the original backup object upload is uncertain; retain its original receipt and do not PUT it again"));
        }
        mutation.prepare(&self.control)?;
        let prepared = self
            .backup_post(
                "/share/generate_upload_url_v2",
                &json!({"file_type":artifact.category.key(),"file_size":artifact.size}),
                true,
            )
            .map_err(|error| mutation.failure(error))?;
        let object = prepared["file_path"]
            .as_str()
            .filter(|value| {
                !value.is_empty()
                    && value.len() <= 4096
                    && !value.chars().any(char::is_control)
                    && output::public(json!(value), &[]) == json!(value)
            })
            .ok_or_else(|| {
                mutation.pending_error(
                    "backup object preparation has no reusable public object reference",
                )
            })?
            .to_owned();
        let url = prepared["upload_url"].as_str().ok_or_else(|| {
            mutation.pending_error("backup object preparation omitted its signed capability")
        })?;
        let url = media::object_url(url, true).map_err(|error| mutation.failure(error))?;
        mutation.remember(json!({"file_path":object,"uploaded":false}))?;
        let mut headers = HeaderMap::new();
        headers.insert(
            CONTENT_TYPE,
            HeaderValue::from_static("application/x-www-form-urlencoded"),
        );
        artifact.file.seek(SeekFrom::Start(0))?;
        let stream = artifact.file.try_clone()?;
        let response = self
            .http
            .put_file(url, headers, stream)
            .map_err(|error| mutation.failure(error))?;
        if response["http_status"] != 200 {
            return Err(mutation.pending_error(
                "backup object PUT did not return the required HTTP 200 acknowledgement",
            ));
        }
        mutation.verified_with(json!({"file_path":object,"uploaded":true,"verification":"http_200_acknowledgement"})).map_err(|_|mutation.pending_error("backup object was accepted; finish saving its original object reference"))?;
        Ok(object)
    }
}
fn scope(hash: &str) -> u64 {
    u64::from_str_radix(&hash[..16], 16).unwrap().max(1)
}
fn form_hash(value: &Value) -> Result<String> {
    Ok(storage::sha256(&storage::identity_json(value)?))
}
fn decoded(value: &Value) -> Value {
    if let Some(text) = value.as_str() {
        crate::input::value(text.as_bytes()).unwrap_or_else(|_| value.clone())
    } else {
        value.clone()
    }
}
fn contains(expected: &Value, actual: &Value) -> bool {
    if let Value::String(expected) = expected {
        return actual
            .as_str()
            .is_some_and(|actual| expected == actual || object_path(expected, actual));
    }
    let actual = decoded(actual);
    match expected {
        Value::Object(fields) => actual.as_object().is_some_and(|actual| {
            fields.iter().all(|(key, value)| {
                matches!(key.as_str(), "select" | "size" | "editModeLayouts")
                    || actual
                        .get(key)
                        .is_some_and(|actual| contains(value, actual))
            })
        }),
        Value::Array(items) => actual.as_array().is_some_and(|rows| {
            if rows.len() != items.len() {
                return false;
            }
            let mut used = BTreeSet::new();
            items.iter().all(|item| {
                rows.iter()
                    .enumerate()
                    .find(|(index, row)| !used.contains(index) && contains(item, row))
                    .is_some_and(|(index, _)| used.insert(index))
            })
        }),
        Value::Null => actual.is_null() || actual == "",
        Value::String(expected) => actual
            .as_str()
            .is_some_and(|actual| expected == actual || object_path(expected, actual)),
        _ => expected == &actual,
    }
}
fn object_path(expected: &str, actual: &str) -> bool {
    fn path(value: &str) -> Option<String> {
        let url = reqwest::Url::parse(value).ok()?;
        if !matches!(url.scheme(), "http" | "https") || url.host_str().is_none() {
            return None;
        }
        Some(url.path().trim_start_matches('/').to_owned())
    }
    match (path(expected), path(actual)) {
        (Some(expected), Some(actual)) => expected == actual,
        (Some(expected), None) => expected == actual.trim_start_matches('/'),
        (None, Some(actual)) => expected.trim_start_matches('/') == actual,
        _ => false,
    }
}
fn empty(value: &Value, array: bool) -> bool {
    let value = decoded(value);
    value.is_null() || value == "" || (array && value.as_array().is_some_and(Vec::is_empty))
}
fn manifest_matches(manifest: &Value, row: &Value) -> bool {
    for (source, target) in [
        ("knowplug_list", "t_Known_plug"),
        ("t_unKnown_list", "t_unKnown_list"),
        ("t_material_list", "t_material_list"),
        ("t_font_list", "t_font_list"),
        ("unknown_plug", "t_unKnown_plug"),
        ("material", "t_material"),
        ("font_hash", "t_font_ncs_hash"),
    ] {
        let expected = &manifest[source];
        let actual = &row[target];
        if expected.is_null() || expected == "" || expected.as_array().is_some_and(Vec::is_empty) {
            if !empty(actual, expected.is_array()) {
                return false;
            }
        } else if !contains(expected, actual) {
            return false;
        }
    }
    let accounts = manifest["wtf"]
        .as_array()
        .unwrap()
        .iter()
        .map(|account| {
            let mut account = account.clone();
            account.as_object_mut().unwrap().remove("id");
            account
        })
        .collect::<Vec<_>>();
    let actual = row
        .get("wtflist")
        .or_else(|| row.get("t_WTF_list"))
        .unwrap_or(&Value::Null);
    if accounts.is_empty() {
        if !empty(actual, true)
            || row
                .get("t_WTF_list")
                .is_some_and(|value| !empty(value, true))
        {
            return false;
        }
    } else if !contains(&json!(accounts), actual) {
        return false;
    }
    wire_uint(row["t_Versionid"].clone(), 0)
        .is_ok_and(|id| Some(id) == manifest["versionid"].as_u64())
}
